/**
 * journal-plan.test.mjs — записи карты проекта в журнале комнаты.
 *
 * Проверяем тавтологию: сервер пишет «Добавил направление «X» по сообщению
 * Михаила», журнал ставит перед причиной «, потому что» — повтор текста
 * (найдено на e2e шага e: «добавил направление «X», потому что Добавил
 * направление «X» по сообщению Михаила») снимается.
 */

import test from 'node:test';
import assert from 'node:assert/strict';

import { untautologize } from '../web/js/views/journal.js';

test('тавтология причины снимается: повтор не дублируется', () => {
  const text = 'добавил направление «Упаковка», потому что Добавил направление «Упаковка» по сообщению Михаила';
  assert.equal(untautologize(text),
    'добавил направление «Упаковка» — по сообщению Михаила');
});

test('чужая причина (не повтор) остаётся как есть', () => {
  const text = 'добавил направление «Упаковка», потому что руководитель разбил работу: договор нужен раньше партии';
  assert.equal(untautologize(text), text);
});

test('повтор названия без слова «направление» тоже снимается (демо-фикстура)', () => {
  const text = 'добавил направление «Продажи и доставка», потому что Добавил «Продажи и доставка»: '
    + 'без каналов набор некуда вести, запуск — после упаковки';
  assert.equal(untautologize(text),
    'добавил направление «Продажи и доставка» — без каналов набор некуда вести, запуск — после упаковки');
  // Причина про другое направление не трогается: там своя мысль.
  const other = 'добавил направление «Упаковка», потому что «Продажи и доставка» ждут упаковку';
  assert.equal(untautologize(other), other);
});

test('повтор названия после двоеточия тоже снимается', () => {
  assert.equal(
    untautologize('изменил направление «Налоги и ИП»: «Налоги и ИП» — готово'),
    'изменил направление «Налоги и ИП» — готово',
  );
  // Причина про другое — не трогаем (это смысл записи, а не повтор).
  assert.equal(
    untautologize('изменил направление «Упаковка и бренд»: Михаил: срок по упаковке — до 20 ноября'),
    'изменил направление «Упаковка и бренд»: Михаил: срок по упаковке — до 20 ноября',
  );
  assert.equal(
    untautologize('предложил карту: 3 направления'),
    'предложил карту: 3 направления',
  );
});

test('полный повтор без остатка — только первая половина, точка не нужна', () => {
  assert.equal(
    untautologize('убрал направление «Цены», потому что убрал направление «Цены»'),
    'убрал направление «Цены»',
  );
  assert.equal(
    untautologize('изменил направление «Смета»: срок сдвинут'),
    'изменил направление «Смета»: срок сдвинут',
  );
  assert.equal(untautologize(''), '');
  assert.equal(untautologize(null), '');
  assert.equal(untautologize('предложил карту: 3 направления'), 'предложил карту: 3 направления');
});
