/**
 * journal-plan.test.mjs — записи карты проекта в журнале комнаты.
 *
 * Проверяем тавтологию: сервер пишет «Добавил часть работы «X» по сообщению
 * Михаила», журнал ставит перед причиной «, потому что» — повтор текста
 * (найдено на e2e шага e: «добавил часть работы «X», потому что Добавил
 * часть работы «X» по сообщению Михаила») снимается.
 */

import test from 'node:test';
import assert from 'node:assert/strict';

import { untautologize } from '../web/js/views/journal.js';

test('тавтология причины снимается: повтор не дублируется', () => {
  const text = 'добавил часть работы «Упаковка», потому что Добавил часть работы «Упаковка» по сообщению Михаила';
  assert.equal(untautologize(text),
    'добавил часть работы «Упаковка» — по сообщению Михаила');
});

test('чужая причина (не повтор) остаётся как есть', () => {
  const text = 'добавил часть работы «Упаковка», потому что руководитель разбил работу: договор нужен раньше партии';
  assert.equal(untautologize(text), text);
});

test('повтор названия без слова «часть работы» тоже снимается (демо-фикстура)', () => {
  const text = 'добавил часть работы «Продажи и доставка», потому что Добавил «Продажи и доставка»: '
    + 'без каналов набор некуда вести, запуск — после упаковки';
  assert.equal(untautologize(text),
    'добавил часть работы «Продажи и доставка» — без каналов набор некуда вести, запуск — после упаковки');
  // Причина про другое часть работы не трогается: там своя мысль.
  const other = 'добавил часть работы «Упаковка», потому что «Продажи и доставка» ждут упаковку';
  assert.equal(untautologize(other), other);
});

test('повтор названия после двоеточия тоже снимается', () => {
  assert.equal(
    untautologize('изменил часть работы «Налоги и ИП»: «Налоги и ИП» — готово'),
    'изменил часть работы «Налоги и ИП» — готово',
  );
  // Причина про другое — не трогаем (это смысл записи, а не повтор).
  assert.equal(
    untautologize('изменил часть работы «Упаковка и бренд»: Михаил: срок по упаковке — до 20 ноября'),
    'изменил часть работы «Упаковка и бренд»: Михаил: срок по упаковке — до 20 ноября',
  );
  assert.equal(
    untautologize('предложил карту: 3 части работы'),
    'предложил карту: 3 части работы',
  );
});

test('полный повтор без остатка — только первая половина, точка не нужна', () => {
  assert.equal(
    untautologize('убрал часть работы «Цены», потому что убрал часть работы «Цены»'),
    'убрал часть работы «Цены»',
  );
  assert.equal(
    untautologize('изменил часть работы «Смета»: срок сдвинут'),
    'изменил часть работы «Смета»: срок сдвинут',
  );
  assert.equal(untautologize(''), '');
  assert.equal(untautologize(null), '');
  assert.equal(untautologize('предложил карту: 3 части работы'), 'предложил карту: 3 части работы');
});
