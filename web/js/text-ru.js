/** Подпись кнопки досылки, когда автообновление свода ВЫКЛЮЧЕНО:
 * «1 ответ ждёт отправки», «3 ответа ждут отправки».
 */
export function pendingAnswersLabel(n) {
  const count = Math.max(0, Math.trunc(Number(n) || 0));
  return countNoun(count, ['ответ', 'ответа', 'ответов']) + ' '
    + pluralVerb(count, ['ждёт', 'ждут']) + ' отправки';
}

/** Словарь по ключу; неизвестный ключ — пустые строки (интерфейс не падает). */
export function term(key) {
  const t = TERMS[String(key || '')];
  if (!t || typeof t !== 'object') return { key: '', name: '', title: '', hint: '', example: '' };
  return {
    key: String(key),
    name: String(t.name || ''),
    title: String(t.title || t.name || ''),
    hint: String(t.hint || ''),
    example: String(t.example || ''),
  };
}

/** Объяснение термина для подсказки «?»: '' — объяснять нечего. */
export function termHint(key) {
  return term(key).hint;
}

