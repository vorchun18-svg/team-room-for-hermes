"""Правила руководителя: оценка задачи и проект «задача → подзадачи» (W30 §2).

Одно место текста. `server/contract.py` включает короткое правило ОДНОЙ строкой
(`contract_project.card_rule(room)`), чтобы текст не жил в общем файле и не
конфликтовал с параллельными пакетами.

Формат комментария-оценки читает `server/projects.py` (маркер `MARK`, ключи
`task_kind/summary/branches`). Меняешь текст — правь и разбор: это одна пара.
"""
from __future__ import annotations

#: Метка комментария, которым руководитель оценивает задачу (W30 §2).
MARK = "[Руководитель · оценка задачи]"
#: Варианты метки, которые сервер тоже понимает (агент может написать чуть иначе).
MARK_ALIASES = (MARK, "[Руководитель · оценка]", "[Руководитель · предложение задач]")

#: Порог, после которого предложение веток обязательно (W30 §2, пакет B).
BIG_CARDS = 6
BIG_DIRECTIONS = 3
MAX_BRANCHES = 8


def card_rule(room: dict | None = None) -> str:
    """Короткое правило для карточки руководителя (уходит в устав одной строкой).

    Тон и длина — как у соседних правил (`approval_rule`, `svod_rule`): ≈800 знаков,
    только то, без чего работа начинается неправильно.
    """
    return " ".join([
        "Оценка задачи — твоя и до работы: разовая («выполним в одной задаче») или объёмная.",
        "Разовая — комментарий `%s` + metadata " % MARK
        + "{\"task_kind\":\"single\",\"summary\":\"<1–2 фразы>\"}; объёмная — "
        "{\"task_kind\":\"big\",\"summary\":\"…\",\"branches\":[{\"id\",\"title\",\"goal\",\"assignee\","
        "\"questions\",\"order\"}]}, ветки 2–%d." % MAX_BRANCHES,
        "Порог: больше %d карточек или %d направлений — предложение обязательно, не копи всё "
        "в одно дерево." % (BIG_CARDS, BIG_DIRECTIONS),
        "Подзадачи создаёт ПРИЛОЖЕНИЕ и только после согласия Михаила (сам корни не создавай): "
        "ветка станет отдельной задачей с тем же критиком и сдачей тебе.",
    ])


def _example_branches() -> str:
    """Нейтральный пример (химчистка): вторая точка приёма → три направления."""
    return ("{\"task_kind\":\"big\",\"summary\":\"Открыть второй пункт приёма: три направления.\","
            "\"branches\":[{\"id\":\"b1\",\"title\":\"Помещение\",\"goal\":\"Найти и оценить помещение "
            "под приём, аренда и сроки\",\"assignee\":\"team-ops\",\"questions\":[\"Какая площадь "
            "нужна?\"],\"order\":1},{\"id\":\"b2\",\"title\":\"Оборудование\",\"goal\":\"Подобрать "
            "машины и цену\",\"assignee\":\"team-cfo\",\"questions\":[],\"order\":2},"
            "{\"id\":\"b3\",\"title\":\"Персонал\",\"goal\":\"Кто работает на точке и сколько это "
            "стоит\",\"assignee\":\"team-lawyer\",\"questions\":[],\"order\":3}]}")


def split_request_body(parent_title: str = "", team: str = "") -> str:
    """Тело карточки руководителю «Подготовь предложение задач по этой задаче» (W30 §2)."""
    lines = [
        "Подготовь предложение задач по этой задаче: оцени, разовая она или объёмная, "
        "и ответь ОДНИМ комментарием к корневой карточке.",
        "Маркер и metadata (иначе приложение не увидит):",
        "`%s`" % MARK,
        "{\"task_kind\":\"single|big\",\"summary\":\"<1–2 фразы по-русски>\","
        "\"branches\":[{\"id\":\"b1\",\"title\":\"…\",\"goal\":\"…\",\"assignee\":\"…\","
        "\"questions\":[\"…\"],\"order\":1}]}",
        "Разовая — kind=single, ветки не нужны. Объёмная — 2–%d веток: title (коротко), goal "
        "(что должно получиться), assignee (профиль из команды комнаты), questions (что ветка "
        "должна решить), order (порядок)." % MAX_BRANCHES,
        "Порог: больше %d карточек или больше %d направлений — предложение обязательно; "
        "не копи всё в одно дерево." % (BIG_CARDS, BIG_DIRECTIONS),
        "Пример (химчистка, «открыть второй пункт приёма»): %s" % _example_branches(),
        "Задачи по веткам создаёт ПРИЛОЖЕНИЕ и только после согласия Михаила: сам карточки не создавай. "
        "Критик каждой подзадачи наследуется от этой задачи.",
    ]
    if team:
        lines.append("Кого можно ставить (профили комнаты): %s." % team)
    if parent_title:
        lines.insert(0, "Задача: «%s»." % parent_title)
    return "\n".join(lines)


def split_card_title() -> str:
    """Заголовок карточки «Разбить на задачи» — по нему же узнаём повтор."""
    return "Предложение задач: разбить на подзадачи"


